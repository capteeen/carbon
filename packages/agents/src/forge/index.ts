/**
 * FORGE: chosen narrative → name, ticker, lore, logo + banner (llm.generateImage),
 * a one-page site, the logo's perceptual hash; emits forge.draft.
 *
 * Metadata goes to pump.fun IPFS only in prepareDeploy(), after Sentinel has
 * cleared the draft, so content that fails the rules is never published.
 * prepareDeploy() emits a second forge.draft with the same content plus
 * metadataUri (and the IPFS image URI as logoUri).
 */
import type { ArgonEvent } from '@argon/core';
import { type AgentContext, AgentRefusal, emit, gate, think } from '../context.js';
import { hashImageBytes } from '../image/phash.js';
import { llmJson, normalizeName, normalizeTicker, obj, optStr, str } from '../json.js';
import { FORGE_PROMPT, FORGE_SCHEMA, FORGE_SYSTEM, fill } from '../prompts/index.js';
import type { Narrative } from '../scout/index.js';
import { renderSite } from './site.js';

export interface Revision {
  name?: string;
  ticker?: string;
  /** Free-text note from the user, passed to the model. */
  note?: string;
  /** Regenerate logo and banner. */
  newArt?: boolean;
}

interface Artifacts {
  logo: Uint8Array;
  logoMime: string;
  banner: Uint8Array;
  bannerMime: string;
  tagline: string;
  narrative: Narrative;
}

export class Forge {
  /** Generated bytes by forge.draft event id (needed for the metadata upload). */
  private readonly artifacts = new Map<string, Artifacts>();

  constructor(private readonly ctx: AgentContext) {}

  async draft(
    narrative: Narrative,
    pick: { name: string; ticker: string },
    opts: { revision?: Revision; previous?: ArgonEvent<'forge.draft'> } = {},
  ): Promise<ArgonEvent<'forge.draft'>> {
    const ctx = this.ctx;
    const { revision, previous } = opts;
    await gate(ctx, 'forge', revision ? 'revise the coin draft' : 'create the coin draft', {
      narrative: narrative.title,
      name: revision?.name ?? pick.name,
      ticker: revision?.ticker ?? pick.ticker,
    });

    const res = await think(ctx, 'forge', {
      system: FORGE_SYSTEM,
      prompt: fill(FORGE_PROMPT, {
        title: narrative.title,
        why: narrative.why,
        name: revision?.name ?? pick.name,
        ticker: revision?.ticker ?? pick.ticker,
        revision: revision
          ? `Revision requested by the user after a Sentinel check: ${revision.note ?? '(no note)'}`
          : '',
      }),
      jsonSchema: FORGE_SCHEMA as unknown as Record<string, unknown>,
      temperature: 0.9,
    });
    const out = obj(llmJson(res), 'forge');
    const name = normalizeName(revision?.name ?? str(out.name, 'name'));
    const ticker = normalizeTicker(revision?.ticker ?? str(out.ticker, 'ticker'));
    if (ticker.length < 2) throw new Error('forge: ticker too short');
    const lore = str(out.lore, 'lore').slice(0, 600);
    const tagline = str(out.tagline, 'tagline').slice(0, 120);

    const prevArt = previous ? this.artifacts.get(previous.id) : undefined;
    let logo: { bytes: Uint8Array; mime: string };
    let banner: { bytes: Uint8Array; mime: string };
    let artNote: string;
    if (prevArt && !revision?.newArt) {
      logo = { bytes: prevArt.logo, mime: prevArt.logoMime };
      banner = { bytes: prevArt.banner, mime: prevArt.bannerMime };
      artNote = 'kept previous art';
    } else {
      if (!ctx.llm.generateImage) throw new AgentRefusal('forge', `LLM provider ${ctx.llm.id} cannot generate images`);
      await ctx.budgets.spend(ctx.launchId, 'forge', 'llm');
      logo = await ctx.llm.generateImage(str(out.logoPrompt, 'logoPrompt'), '1:1');
      await ctx.budgets.spend(ctx.launchId, 'forge', 'llm');
      banner = await ctx.llm.generateImage(str(out.bannerPrompt, 'bannerPrompt'), '3:1');
      artNote = 'generated logo and banner';
    }
    const logoHash = hashImageBytes(logo.bytes);

    const ext = (m: string) => (m.includes('jpeg') ? 'jpg' : 'png');
    const logoAsset = await ctx.assets.put(ctx.launchId, `logo-${logoHash}.${ext(logo.mime)}`, logo.bytes, logo.mime);
    const bannerAsset = await ctx.assets.put(ctx.launchId, `banner-${logoHash}.${ext(banner.mime)}`, banner.bytes, banner.mime);
    const html = renderSite({ name, ticker, lore, tagline, logoUri: logoAsset.uri, bannerUri: bannerAsset.uri });
    const site = await ctx.assets.put(ctx.launchId, `site-${ticker.toLowerCase()}.html`, new TextEncoder().encode(html), 'text/html; charset=utf-8');

    const reasoning = optStr(out.reasoning) ?? `Drafted ${name} ($${ticker}) for "${narrative.title}".`;
    const e = await emit(
      ctx,
      'forge',
      'forge.draft',
      { name, ticker, lore, logoUri: logoAsset.uri, logoHash, bannerUri: bannerAsset.uri, siteUri: site.uri },
      `${reasoning} (${artNote}; logo dHash ${logoHash.slice(0, 8)})`,
    );
    this.artifacts.set(e.id, { logo: logo.bytes, logoMime: logo.mime, banner: banner.bytes, bannerMime: banner.mime, tagline, narrative });
    return e;
  }

  /** After Sentinel clears the draft: upload pump.fun metadata, emit the deploy-ready forge.draft. */
  async prepareDeploy(draft: ArgonEvent<'forge.draft'>): Promise<ArgonEvent<'forge.draft'>> {
    const ctx = this.ctx;
    const art = this.artifacts.get(draft.id);
    if (!art) throw new AgentRefusal('forge', 'draft artifacts not held by this Forge; re-draft before deploy');
    await gate(ctx, 'forge', 'upload coin metadata to pump.fun', { name: draft.payload.name, ticker: draft.payload.ticker });
    const d = draft.payload;
    const { metadataUri, imageUri } = await ctx.chain.uploadMetadata({
      name: d.name,
      symbol: d.ticker,
      description: d.lore,
      image: art.logo,
      website: d.siteUri,
    });
    const e = await emit(
      ctx,
      'forge',
      'forge.draft',
      { ...d, logoUri: imageUri, metadataUri },
      `Sentinel cleared $${d.ticker}; uploaded name, ticker, lore, logo and site link as pump.fun metadata.`,
    );
    this.artifacts.set(e.id, art);
    return e;
  }
}
